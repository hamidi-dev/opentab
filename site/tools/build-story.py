#!/usr/bin/env python3
"""Extract the landing hero's small, synthetic case study from the site report.

Only run against site/report.html, built by showcase.sh. The checked-in snapshot
lets the lightweight hero render without downloading the full report.
"""

import datetime as dt
import json
import re
from pathlib import Path

SITE = Path(__file__).resolve().parents[1]
SESSION = "ses_0a9f3c2e71b4d58e6f20c1a7b9"


def token_economics(report):
    """Use the report's own rate snapshot, including context tiers and 1h writes.

    Mirrors web/page.py's tokenEconomics: five additive token categories;
    reasoning uses output rates and 1h writes replace a subset of cache writes.
    Recorded dollars cannot be split by token type, so this is all list rates.
    """
    tokens = [0] * 5
    costs = [0.0] * 5
    prices = report["whatif"]
    local = set(prices["local"])
    skipped_local_tokens = 0
    for session in report["workflows"]:
        for row in report["models"][session["id"]]:
            model = row["model"]
            if model in local:
                skipped_local_tokens += sum(row["tok"][:5])
                continue
            samples = row.get("pricing")
            if samples is None:
                samples = [{"context": row.get("context"), "tok": row["tok"]}]
            for sample in samples:
                rate = prices["rates"][model]
                context = sample["context"]
                if context is not None:
                    for tier in prices["tiers"].get(model, []):
                        if context > tier["context"]:
                            rate = tier["price"]
                tok = sample["tok"]
                long_write = min(max(tok[5] if len(tok) > 5 else 0, 0), tok[4])
                amounts = [
                    tok[0] * rate[0],
                    tok[1] * rate[1],
                    tok[2] * rate[1],
                    tok[3] * rate[2],
                    (tok[4] - long_write) * rate[3] + long_write * (rate[4] or rate[3]),
                ]
                for i in range(5):
                    tokens[i] += tok[i]
                    costs[i] += amounts[i] / 1_000_000
    categories = [
        (3, "cache-read", "Cache read"),
        (1, "output", "Output"),
        (4, "cache-write", "Cache write"),
        (0, "input", "Uncached input"),
        (2, "reasoning", "Reasoning"),
    ]
    types = [
        {"key": key, "label": label, "tokens": tokens[i], "cost": round(costs[i], 6)}
        for i, key, label in categories
    ]
    return {
        "tokens": sum(t["tokens"] for t in types),
        "cost": round(sum(t["cost"] for t in types), 6),
        "basis": "API list-price estimate",
        "skippedLocalTokens": skipped_local_tokens,
        "types": types,
    }


def main():
    html = (SITE / "report.html").read_text()
    match = re.search(
        r'<script type="application/json" id="opentab-data">(.*?)</script>',
        html,
        re.S,
    )
    if not match:
        raise SystemExit("story: report has no data")
    report = json.loads(match[1])
    sessions = report["workflows"]
    session = next(s for s in sessions if s["id"] == SESSION)
    details = json.loads((SITE / "report-details" / report["detailFiles"][SESSION]).read_text())
    day = session["date"][:10]
    daily = {}
    for s in sessions:
        key = s["date"][:10]
        daily[key] = daily.get(key, 0) + s["api"]
    start = dt.date.fromisoformat(min(daily))
    end = dt.date.fromisoformat(max(daily))
    roots = [t for t in details["turns"] if t["depth"] == 0]
    story = {
        "provenance": "Synthetic showcase. Generated by site/tools/build-story.py; not customer usage.",
        "session": {
            k: session[k]
            for k in ("id", "title", "source", "date", "dur", "real", "api", "tokens", "subagents")
        },
        "days": [
            {"date": date.isoformat(), "cost": round(daily.get(date.isoformat(), 0), 6)}
            for date in (start + dt.timedelta(days=i) for i in range((end - start).days + 1))
        ],
        "daySessions": [
            {k: s[k] for k in ("id", "title", "api")}
            for s in sorted(sessions, key=lambda s: s["api"], reverse=True)
            if s["date"].startswith(day)
        ],
        "nodes": [
            {k: n[k] for k in ("title", "agent", "depth", "real")} for n in report["nodes"][SESSION]
        ],
        "prompt": roots[0]["promptFull"],
        "firstTurns": [{k: t[k] for k in ("time", "tools", "ctx")} for t in roots[:4]],
        "context": [p["v"] for p in details["context"]["points"]],
        "turns": len(details["turns"]),
        "calls": len(details["toolCalls"]),
        "economics": token_economics(report),
    }
    output = SITE / "media" / "hero-story.json"
    output.write_text(json.dumps(story, separators=(",", ":")) + "\n")
    print(f"hero-story.json: {output.stat().st_size:,} bytes, {session['title']}")


if __name__ == "__main__":
    main()
